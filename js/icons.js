const attrName = (name) => name.replace(/[A-Z]/g, (letter) => "-" + letter.toLowerCase());

const draw = (nodes) => nodes.map(([tag, attrs]) => {
  const parts = Object.entries(attrs)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${attrName(key)}="${value}"`);
  return `<${tag} ${parts.join(" ")}/>`;
}).join("");

export const icon = (name, size = 20) => {
  const nodes = ICONS[name];
  if (!nodes) return "";
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" aria-hidden="true">${draw(nodes)}</svg>`;
};

